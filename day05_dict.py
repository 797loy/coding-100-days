# day05_dict.py 学习字典：按键存值取值

# 1) 建一个字典：一笔交易
txn = {"日期": "2026-10-01", "类别": "餐饮", "类型": "支出", "金额": 35}

# 2) 按键取值
print("类别是：", txn["类别"])
print("金额是：", txn["金额"])

# 3) 新增一对、改一个值
txn["支付方式"] = "微信"      # 新增
txn["金额"] = 38            # 修改
print("改完后的字典：", txn)

# 4) for 遍历：打印每个键和值
for key in txn:
    print(key, "→", txn[key])


