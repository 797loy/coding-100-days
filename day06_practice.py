# day06_practice.py 把"按类别统计支出"封装成可复用函数

def sum_by_category(txns):
    """传入交易列表(每个元素是含 类别/类型/金额 的字典)，返回各类别支出合计字典"""
    total_by_cat = {}
    for row in txns:
        if row["类型"] == "支出":
            cat = row["类别"]
            if cat not in total_by_cat:
                total_by_cat[cat] = 0
            total_by_cat[cat] += row["金额"]
    return total_by_cat          # 把统计结果整个字典交出去

# 第一批数据
txns1 = [
    {"类别": "餐饮", "类型": "支出", "金额": 35},
    {"类别": "工资", "类型": "收入", "金额": 8000},
    {"类别": "餐饮", "类型": "支出", "金额": 28},
    {"类别": "购物", "类型": "支出", "金额": 300},
]

# 第二批数据（换一批，直接复用同一个函数，不用改函数内部）
txns2 = [
    {"类别": "交通", "类型": "支出", "金额": 6},
    {"类别": "交通", "类型": "支出", "金额": 12},
    {"类别": "房租", "类型": "支出", "金额": 1500},
    {"类别": "奖金", "类型": "收入", "金额": 2000},
]

r1 = sum_by_category(txns1)
r2 = sum_by_category(txns2)
print("第一批：", r1)
print("第二批：", r2)

# 函数返回的是字典，可以继续按键取值
print("第二批房租：", r2["房租"])
