# day05_practice.py 用字典当累加器:统计每个类别花了多少钱
# 1）多笔交易，列表里面装字典
txns = [
    {"类别": "餐饮", "类型": "支出", "金额": 35},
    {"类别": "工资", "类型": "收入", "金额": 8000},
    {"类别": "交通", "类型": "支出", "金额": 6},
    {"类别": "餐饮", "类型": "支出", "金额": 28},
    {"类别": "购物", "类型": "支出", "金额": 300},
    {"类别": "餐饮", "类型": "支出", "金额": 12},
]
# 2）空字典当累加器
total_by_cat={}
# 3)循环每一笔
for row in txns:
    if row["类型"]=="支出":  # 只统计支出
        cat=row["类别"]
        if cat not in total_by_cat:  # 如果这个类别还没有出现过
            total_by_cat[cat]=0  # 初始化为0
        total_by_cat[cat]+=row["金额"]  # 累加金额
# 4)打印结果
for cat in total_by_cat:
    print(cat, "共花了", total_by_cat[cat])